export function getSportsIconName(icon: SportsIcon, lang: string = 'it'): string {
  const normLang = (lang || 'it').toLowerCase();
  if (normLang === 'de') return icon.nameDe || icon.nameIt || icon.name;
  if (normLang === 'en') return icon.nameEn || icon.nameIt || icon.name;
  return icon.nameIt || icon.name;
}

export function getSportsIconDescription(icon: SportsIcon, lang: string = 'it'): string {
  const normLang = (lang || 'it').toLowerCase();
  if (normLang === 'de') return icon.descriptionDe || icon.descriptionIt || icon.description || '';
  if (normLang === 'en') return icon.descriptionEn || icon.descriptionIt || icon.description || '';
  return icon.descriptionIt || icon.description || '';
}

export function getAllSportsIcons(customIcons: SportsIcon[] = []): SportsIcon[] {
  const customList: SportsIcon[] = [];
  try {
    const raw = localStorage.getItem('dns_custom_sports_icons');
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed)) {
        customList.push(...parsed);
      }
    }
  } catch {
    // ignore
  }

  for (const c of customIcons) {
    if (!customList.some(i => i.id === c.id)) {
      customList.unshift(c);
    }
  }

  const map = new Map<string, SportsIcon>();
  [...SPORTS_ICONS, ...customList].forEach(icon => {
    if (icon && icon.id) {
      map.set(icon.id, icon);
    }
  });

  return Array.from(map.values());
}
